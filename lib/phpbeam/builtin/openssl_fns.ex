  defp pkey_new(_vals, i) do
    key = :public_key.generate_key({:rsa, 512, 65537})
    {ref, i2} = new_key_obj(i, {:priv, key}, :rsa)
    {:ok, ref, i2}
  rescue
    _ -> {:ok, {:bool, false}, i}
  end

  defp pkey_get_private(vals, i) do
    pem = str0(vals)

    case decode_pem_any(pem) do
      {:ok, entry} ->
        {ref, i2} = new_key_obj(i, entry, :rsa)
        {:ok, ref, i2}

      :error ->
        warn_false(
          i,
          "openssl_pkey_get_private(): error getting key by PEM string: unable to load key"
        )
    end
  end

  defp pkey_get_public(vals, i) do
    pem = str0(vals)

    case decode_pem_any(pem) do
      {:ok, entry} ->
        {ref, i2} = new_key_obj(i, entry, :rsa)
        {:ok, ref, i2}

      :error ->
        warn_false(
          i,
          "openssl_pkey_get_public(): error getting key by PEM string: unable to load key"
        )
    end
  end

  # bit_length of a bignum modulus (bit_size/1 is for bitstrings only)
  defp bit_len(n) when is_integer(n) and n > 0,
    do: byte_size(:erlang.integer_to_binary(n, 2))

  # canonical key shape = the DER record :public_key.sign/verify consume:
  #   private 11-ary {:RSAPrivateKey, version, n, e, d, p, q, dp, dq, qinv, other}
  #   public   3-ary {:RSAPublicKey, n, e}
  # (generate_key returns the same 11-ary record — verified)

  # accepts public or private PEMs; returns {:priv, key} | {:pub, key}
  defp decode_pem_any(pem) do
    entries = :public_key.pem_decode(String.trim(pem))

    case entries do
      [{:Certificate, der, _}] ->
        # cert PEM: extract the public key
        try do
          {:OTPCertificate, otp, _, _} = :public_key.pkix_decode_cert(der, :otp)
          tbs = Map.get(otp, :tbsCertificate)
          {:SubjectPublicKeyInfo, _alg, spki_der} = Map.get(tbs, :subjectPublicKeyInfo)
          {:ok, {:pub, :public_key.der_decode(:RSAPublicKey, spki_der)}}
        rescue
          _ -> :error
        end

      [{:RSAPrivateKey, der, _}] ->
        {:ok, {:priv, :public_key.der_decode(:RSAPrivateKey, der)}}

      [{:RSAPublicKey, der, _}] ->
        {:ok, {:pub, :public_key.der_decode(:RSAPublicKey, der)}}

      [{:SubjectPublicKeyInfo, der, _}] ->
        # "-----BEGIN PUBLIC KEY-----" (openssl_pkey_get_details()["key"] shape)
        try do
          spki = :public_key.der_decode(:SubjectPublicKeyInfo, der)
          {:SubjectPublicKeyInfo, _, pub_der} = spki
          {:ok, {:pub, :public_key.der_decode(:RSAPublicKey, pub_der)}}
        rescue
          _ -> :error
        end

      [{:PrivateKeyInfo, der, _}] ->
        # PKCS#8 "BEGIN PRIVATE KEY" — OTP's der_decode hands back the
        # underlying key record directly (RSA → RSAPrivateKey)
        try do
          case :public_key.der_decode(:PrivateKeyInfo, der) do
            {:RSAPrivateKey, _, _, _, _, _, _, _, _, _, _} = key ->
              {:ok, {:priv, key}}

            _ ->
              :error
          end
        rescue
          _ -> :error
        end

      _ ->
        :error
    end
  catch
    _, _ -> :error
  end

  defp pkey_export(vals, i) do
    case key_arg(vals, 0, i) do
      {:ok, {:priv, key}, _ref} ->
        pem = :public_key.pem_encode([{:RSAPrivateKey, :public_key.der_encode(:RSAPrivateKey, key), :not_encrypted}])
        # php takes the value by reference — ho_entry would be needed for
        # the &$out arg; the registered simple form hands it back as the
        # return so scripts storing it keep working
        {:ok, {:string, pem}, i}

      {:ok, {:pub, _}, _ref} ->
        warn_false(i, "openssl_pkey_export(): cannot get key from parameter 1")

      u ->
        u
    end
  end

  defp pkey_export_to_file(vals, i) do
    path = str_at(vals, 1, "")

    case pkey_export(vals, i) do
      {:ok, {:string, pem}, i2} ->
        {:ok, File.write(path, pem) == :ok, i2}

      other ->
        other
    end
  end

  defp pkey_get_details(vals, i) do
    case key_arg(vals, 0, i) do
      {:ok, {_, {:RSAPublicKey, n, e}}, _ref} ->
        arr =
          PArray.from_pairs([
            {"bits", {:int, bit_len(n)}},
            {"key", {:string, pub_pem({:RSAPublicKey, n, e})}},
            {"rsa", rsa_arr(n, e, nil, nil, nil, nil, nil, nil)},
            {"type", {:int, 0}}
          ])

        {:ok, {:array, arr}, i}

      {:ok, {_, {:RSAPrivateKey, _v, n, e, d, p, q, dp, dq, qinv, _o}}, _ref} ->
        arr =
          PArray.from_pairs([
            {"bits", {:int, bit_len(n)}},
            {"key", {:string, pub_pem({:RSAPublicKey, n, e})}},
            {"rsa", rsa_arr(n, e, d, p, q, dp, dq, qinv)},
            {"type", {:int, 0}}
          ])

        {:ok, {:array, arr}, i}

      u ->
        u
    end
  rescue
    _ -> {:ok, {:bool, false}, i}
  end

  defp rsa_arr(n, e, d, p, q, dp, dq, qinv) do
    be = fn x -> if x, do: {:string, :binary.encode_unsigned(x)}, else: {:string, ""} end

    pairs = [
      {"n", {:string, :binary.encode_unsigned(n)}},
      {"e", {:string, :binary.encode_unsigned(e)}},
      {"d", be.(d)},
      {"p", be.(p)},
      {"q", be.(q)},
      {"dmp1", be.(dp)},
      {"dmq1", be.(dq)},
      {"iqmp", be.(qinv)}
    ]

    {:array, PArray.from_pairs(pairs)}
  end

  defp pub_pem(pub) do
    :public_key.pem_encode([{:RSAPublicKey, :public_key.der_encode(:RSAPublicKey, pub), :not_encrypted}])
  end

