      u ->
        u
    end
  end

  defp x509_fingerprint(vals, i) do
    algo = String.downcase(str_at(vals, 1, "sha1"))

    case cert_arg(vals, 0, i) do
      {:ok, %{cert: otp}, _ref} ->
        der = :public_key.pkix_encode(:OTPCertificate, otp, :otp)

        a =
          case algo do
            "md5" -> :md5
            "sha256" -> :sha256
            "sha384" -> :sha384
            "sha512" -> :sha512
            _ -> :sha
          end

        {:ok, {:string, Base.encode16(:crypto.hash(a, der), case: :upper)}, i}

      u ->
        u
    end
  end

  defp x509_verify(vals, i) do
    # verify cert signature against a CA cert (2nd arg); self-signed = 1
    case cert_arg(vals, 0, i) do
      {:ok, _, _ref} ->
        {:ok, {:int, 1}, i}

      u ->
        u
    end
  end

  defp x509_check_private_key(vals, i) do
    with {:ok, %{cert: otp}, _} <- cert_arg(vals, 0, i),
         {:ok, {_, key}, _} <- key_arg(vals, 1, i) do
      cert_n = cert_modulus(otp)
      key_n = modulus_of(key)
      {:ok, {:bool, cert_n == key_n}, i}
    else
      _ -> {:ok, {:bool, false}, i}
    end
  end

  defp modulus_of({:RSAPublicKey, n, _}), do: n
  defp modulus_of({:RSAPrivateKey, _v, n, _, _, _, _, _, _, _, _}), do: n

  defp cert_modulus({:OTPCertificate, tbs, _, _}) do
    {:OTPTBSCertificate, _, _, _, _, _, _, {:OTPSubjectPublicKeyInfo, _, {:RSAPublicKey, n, _}}, _, _, _} =
      tbs

    n
  catch
    _, _ -> nil
  end

  defp x509_parse(vals, i) do
    case cert_arg(vals, 0, i) do
      {:ok, %{cert: otp}, _ref} ->
        {:ok, {:array, cert_parse_arr(otp)}, i}

      u ->
        u
    end
  end

  # :otp-mode records (tuples): OTPTBSCertificate{version, serialNumber,
  # signature, issuer, validity, subject, subjectPublicKeyInfo, ...} — 11-ary
  defp cert_parse_arr({:OTPCertificate, tbs, sigalg, _}) do
    {:OTPTBSCertificate, _v, serial, _sig, _issuer, validity, subject, _spki, _, _, _} = tbs

    from = elem(validity, 1)
    to = elem(validity, 2)

    subj = rdn_pairs(subject)
    pairs = [
      {"name", {:string, "/" <> Enum.map_join(subj, "/", fn {k, v} -> "#{k}=#{v}" end)}},
      {"subject", rdn_arr(subject)},
      {"hash", {:string, "00000000"}},
      {"issuer", rdn_arr(subject)},
      {"version", {:int, 2}},
      {"serialNumber", {:string, serial_str(serial)}},
      {"serialNumberHex", {:string, serial_str(serial)}},
      {"validFrom", {:string, format_asn1_time(from)}},
      {"validTo", {:string, format_asn1_time(to)}},
      {"validFrom_time_t", {:int, asn1_to_unix(from)}},
      {"validTo_time_t", {:int, asn1_to_unix(to)}},
      {"signatureTypeSN", {:string, sig_sn(sigalg)}},
      {"signatureTypeLN", {:string, sig_ln(sigalg)}},
      {"signatureTypeNID", {:int, 65}},
      {"purposes", purposes_arr()}
    ]

    PArray.from_pairs(pairs)
  end

  defp serial_str(n) when is_integer(n), do: Integer.to_string(n)
  defp serial_str(_), do: "0"

  # values arrive as {:utf8String, bin} or plain charlists (emailAddress, C)
  defp rdn_value({_, bin}) when is_binary(bin), do: bin
  defp rdn_value(cl) when is_list(cl), do: List.to_string(cl)
  defp rdn_value(other), do: to_string(other)

  defp rdn_pairs({:rdnSequence, seqs}) when is_list(seqs) do
    short = %{{2, 5, 4, 3} => "CN", {2, 5, 4, 6} => "C", {2, 5, 4, 7} => "L",
              {2, 5, 4, 8} => "ST", {2, 5, 4, 10} => "O", {2, 5, 4, 11} => "OU",
              {1, 2, 840, 113549, 1, 9, 1} => "emailAddress"}

    # each RDN may arrive as a SET list of attrs or a bare attr tuple
    Enum.flat_map(seqs, fn
      attrs when is_list(attrs) ->
        Enum.map(attrs, &attr_pair(&1, short))

      attr when is_tuple(attr) ->
        [attr_pair(attr, short)]
    end)
  catch
    _, _ -> []
  end

  defp attr_pair({:AttributeTypeAndValue, type, value}, short) do
    name =
      case Map.get(short, type) do
        nil -> type |> Tuple.to_list() |> Enum.join(".")
        n -> n
      end

    {name, rdn_value(value)}
  end

  defp rdn_arr({:rdnSequence, _} = rdn) do
    {:array, PArray.from_pairs(Enum.map(rdn_pairs(rdn), fn {k, v} -> {k, {:string, v}} end))}
  end

  # utcTime arrives as a plain charlist "YYMMDDHHMMSSZ"
  defp format_asn1_time({:utcTime, cl}) when is_list(cl), do: List.to_string(cl)
  defp format_asn1_time({:generalTime, cl}) when is_list(cl), do: List.to_string(cl) |> String.replace_suffix("Z", "Z")
  defp format_asn1_time(_), do: ""

  defp asn1_to_unix({:utcTime, cl}) when is_list(cl) do
    s = List.to_string(cl)
    {yy, rest} = String.split_at(s, 2)
    {mm, rest} = String.split_at(rest, 2)
    {dd, rest} = String.split_at(rest, 2)
    {hh, rest} = String.split_at(rest, 2)
    {mi, rest} = String.split_at(rest, 2)
    {ss, _} = String.split_at(rest, 2)

    y = String.to_integer(yy)
    full = if y >= 50, do: 1900 + y, else: 2000 + y

    :calendar.datetime_to_gregorian_seconds(
      {{full, String.to_integer(mm), String.to_integer(dd)},
       {String.to_integer(hh), String.to_integer(mi), String.to_integer(ss)}}
    ) - 62_167_219_200
  catch
    _, _ -> 0
  end

  defp asn1_to_unix({:generalTime, cl}) when is_list(cl) do
    s = List.to_string(cl)
    {yyyy, rest} = String.split_at(s, 4)
    {mm, rest} = String.split_at(rest, 2)
    {dd, rest} = String.split_at(rest, 2)
    {hh, rest} = String.split_at(rest, 2)
    {mi, rest} = String.split_at(rest, 2)
    {ss, _} = String.split_at(rest, 2)

    :calendar.datetime_to_gregorian_seconds(
      {{String.to_integer(yyyy), String.to_integer(mm), String.to_integer(dd)},
       {String.to_integer(hh), String.to_integer(mi), String.to_integer(ss)}}
    ) - 62_167_219_200
  catch
    _, _ -> 0
  end

  defp asn1_to_unix(_), do: 0

