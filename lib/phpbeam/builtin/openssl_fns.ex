defmodule PhpBeam.Builtin.OpensslFns do
  @moduledoc """
  ext/openssl over OTP :crypto / :public_key — the cryptographic core:
  symmetric ciphers (aes cbc/ctr/ofb/gcm families through
  crypto_one_time, PKCS7 padding by default, base64 output unless
  OPENSSL_RAW_DATA), digests, RSA sign/verify (PKCS1 v1.5 — the common
  OPENSSL_ALGO_* set), RSA public/private encrypt+decrypt pairs, and the
  OpenSSLAsymmetricKey / OpenSSLCertificate objects carrying decoded keys
  in dt_state. CSR/CMS/PKCS7/PKCS12 families are stubbed (deferred.md).

  php's aes-128-cbc raw output byte-verified against the local php 8.4
  (same OpenSSL padding); signatures verified against a fixed 512-bit
  fixture generated by php itself.
  """

