  defp pad7(bin) do
    n = 16 - rem(byte_size(bin), 16)
    bin <> :binary.copy(<<n>>, n)
  end

  defp unpad7(bin) do
    sz = byte_size(bin)

    if sz > 0 do
      <<last>> = binary_part(bin, sz - 1, 1)

      if last in 1..16 and last <= sz do
        tail = binary_part(bin, sz - last, last)
        if :binary.copy(<<last>>, last) == tail, do: binary_part(bin, 0, sz - last), else: bin
      else
        bin
      end
    else
      bin
    end
  end

