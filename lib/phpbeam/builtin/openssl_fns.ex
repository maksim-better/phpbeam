  defp x509_read(vals, i) do
    pem = str0(vals)

    with [{:Certificate, der, _}] <- :public_key.pem_decode(String.trim(pem)),
         {:OTPCertificate, _, _, _} = otp <- :public_key.pkix_decode_cert(der, :otp) do
      {ref, i2} = new_cert_obj(i, otp, pem)
      {:ok, ref, i2}
    else
      _ ->
        # cert objects pass through
        case Enum.at(vals, 0) do
          {:object, _} = ref ->
            o = Eval.get_object(i, ref)
            if o.class == "opensslcertificate", do: {:ok, ref, i}, else: warn_false(i, "openssl_x509_read(): supplied parameter cannot be coerced into an X509 certificate!")

          _ ->
            warn_false(i, "openssl_x509_read(): supplied parameter cannot be coerced into an X509 certificate!")
        end
    end
  catch
    _, _ -> {:ok, {:bool, false}, i}
  end

