  defp key_arg(vals, pos, i) do
    case Enum.at(vals, pos) do
      {:object, _} = ref ->
        o = Eval.get_object(i, ref)

        case Map.get(Map.get(o, :dt_state) || %{}, :key) do
          nil ->
            type_error(
              i,
              "Argument #2 must be of type OpenSSLAsymmetricKey",
              PhpBeam.Value.gettype(ref)
            )

          key ->
            {:ok, key, ref}
        end

      {:string, pem} ->
        case decode_pem_any(pem) do
          {:ok, key} -> {:ok, key, nil}
          :error -> bad_key(i)
        end

      _ ->
        type_error(i, "Argument #2 must be of type OpenSSLAsymmetricKey", "bool")
    end
  end

  defp bad_key(i) do
    warn_false(
      i,
      "openssl_pkey_get_private(): error getting key by PEM string: unable to load key"
    )
  end

  defp cert_arg(vals, pos, i) do
    case Enum.at(vals, pos) do
      {:object, _} = ref ->
        o = Eval.get_object(i, ref)

        case Map.get(Map.get(o, :dt_state) || %{}, :cert) do
          nil -> {:error, :not_cert}
          _ -> {:ok, o.dt_state, ref}
        end

      {:string, pem} ->
        case x509_read([{:string, pem}], i) do
          {:ok, {:object, _} = ref2, i2} ->
            o = Eval.get_object(i2, ref2)
            {:ok, o.dt_state, ref2}

          _ ->
            {:error, :not_cert}
        end

      _ ->
        {:error, :not_cert}
    end
  end

  defp type_error(i, msg, given) do
    i2 = PhpBeam.Interp.push_frame(i, "openssl", [])

    {obj, i3} =
      Eval.materialize_native({:native_error, "TypeError", "openssl(): #{msg}, #{given} given"}, i2)

    {:unwind, {:php_throw, obj}, i3}
  end

  defp value_error(i, msg) do
    i2 = PhpBeam.Interp.push_frame(i, "openssl", [])
    {obj, i3} = Eval.materialize_native({:native_error, "ValueError", msg}, i2)
    {:unwind, {:php_throw, obj}, i3}
  end

  defp warn_false(i, msg) do
