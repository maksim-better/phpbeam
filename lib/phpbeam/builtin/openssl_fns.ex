  # flags: OPENSSL_RAW_DATA=1 base64 off; ZERO_PADDING=2 disables PKCS7
  defp sym_encrypt(vals, i) do
    data = str0(vals)
    cipher = String.downcase(str_at(vals, 1, ""))
    key = str_at(vals, 2, "")
    flags = int_at(vals, 3, 0)
    iv = str_at(vals, 4, "")

    with {:ok, {klen, ivlen, {mode, pad}}} <- cipher_lookup(cipher, i),
         true <- byte_size(key) == klen || {:key_err, cipher},
         true <- byte_size(iv) == ivlen || {:iv_err, cipher} do
      raw_out? = Bitwise.band(flags, 1) != 0
      no_pad? = Bitwise.band(flags, 2) != 0

      ct =
        case mode do
          :aes_cbc128 ->
            :crypto.crypto_one_time(aes_cbc_name(klen), key, iv, if(no_pad?, do: data, else: pad7(data)), true)

          :aes_ctr -> :crypto.crypto_one_time(aes_ctr_name(klen), key, iv, data, true)
          :aes_ofb128 -> :crypto.crypto_one_time(aes_ofb_name(klen), key, iv, data, true)
          :aes_cfb128 -> :crypto.crypto_one_time(aes_cfb_name(klen), key, iv, data, true)
          :aes_gcm -> :crypto.crypto_one_time_aead(aes_gcm_name(klen), key, iv, data, <<>>, 16, true) |> elem(0)
          _ -> :erlang.error(:unsupported)
        end

      out = if raw_out?, do: ct, else: Base.encode64(ct)
      {:ok, {:string, out}, i}
    else
      {:key_err, _} -> warn_false(i, "openssl_encrypt(): Key length must be an integer greater than 0")
      {:iv_err, _} ->
        warn_false(
          i,
          "openssl_encrypt(): IV passed is only #{byte_size(iv)} bytes long but cipher expects an IV of precisely #{iv_len_of(cipher)} bytes, padding with zeros"
        )
      :error -> {:ok, {:bool, false}, i}
    end
  rescue
    _ -> {:ok, {:bool, false}, i}
  end

  defp sym_decrypt(vals, i) do
    data = str0(vals)
    cipher = String.downcase(str_at(vals, 1, ""))
    key = str_at(vals, 2, "")
    flags = int_at(vals, 3, 0)
    iv = str_at(vals, 4, "")

    raw_in? = Bitwise.band(flags, 1) != 0
    no_pad? = Bitwise.band(flags, 2) != 0

    bin =
      if raw_in? do
        data
      else
        case Base.decode64(data) do
          {:ok, d} -> d
          :error -> nil
        end
      end

    with {:ok, bin2} when is_binary(bin2) <- {:ok, bin},
         {:ok, {klen, ivlen, {mode, _}}} <- cipher_lookup(cipher, i),
         true <- byte_size(key) == klen || {:key_err, :ok},
         true <- byte_size(iv) == ivlen || {:iv_err, ivlen} do
      pt =
        case mode do
          :aes_cbc128 ->
            raw = :crypto.crypto_one_time(aes_cbc_name(klen), key, iv, bin2, false)
            if(no_pad?, do: raw, else: unpad7(raw))

          :aes_ctr -> :crypto.crypto_one_time(aes_ctr_name(klen), key, iv, bin2, false)
          :aes_ofb128 -> :crypto.crypto_one_time(aes_ofb_name(klen), key, iv, bin2, false)
          :aes_cfb128 -> :crypto.crypto_one_time(aes_cfb_name(klen), key, iv, bin2, false)
          :aes_gcm -> :crypto.crypto_one_time_aead(aes_gcm_name(klen), key, iv, bin2, <<>>, false) |> elem(0)
          _ -> :erlang.error(:unsupported)
        end

      case pt do
        :error ->
          warn_false(i, "openssl_decrypt(): Failed to decrypt base64 data")

        plain ->
          {:ok, {:string, plain}, i}
      end
    else
      {:ok, nil} -> warn_false(i, "openssl_decrypt(): Failed to decode base64 data")
      {:key_err, _} -> warn_false(i, "openssl_decrypt(): Key length must be an integer greater than 0")
      {:iv_err, ivlen2} -> warn_false(i, "openssl_decrypt(): IV passed is only #{byte_size(iv)} bytes long but cipher expects an IV of precisely #{ivlen2} bytes, padding with zeros")
      :error -> {:ok, {:bool, false}, i}
    end
  rescue
    _ -> {:ok, {:bool, false}, i}
  end

  defp iv_len_of(name) do
    case Map.get(@ciphers, String.downcase(name)) do
      {_, iv, _} -> iv
      nil -> 16
    end
  end

  defp cipher_lookup(name, i) do
    case Map.get(@ciphers, String.downcase(name)) do
      nil -> warn_false(i, "openssl_encrypt(): Unknown cipher algorithm")
      spec -> {:ok, spec}
    end
  end

