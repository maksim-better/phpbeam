  # ────────────────────────── envelope (seal/open) ──────────────────────────

  defp seal(vals, i) do
    data = str0(vals)
    cipher = String.downcase(str_at(vals, 3, "aes-128-cbc"))

    case cipher_key_iv(cipher, i) do
      {:ok, klen, _ivlen} ->
        # one random key per call; encrypt it with each public key
        key = :crypto.strong_rand_bytes(klen)

        keys =
          vals
          |> Enum.drop(1)
          |> Enum.flat_map(fn
            {:array, arr} -> PArray.values(arr)
            v -> [v]
          end)
          |> Enum.filter(&match?({:object, _}, &1))

        {envs, i2} =
          Enum.reduce(keys, {[], i}, fn ref, {acc, ia} ->
            o = Eval.get_object(ia, ref)

            case Map.get(Map.get(o, :dt_state) || %{}, :key) do
              {_, k} ->
                pub = to_pub(k)
                {[{:string, :public_key.encrypt_public(key, pub)} | acc], ia}

              _ ->
                {acc, ia}
            end
          end)

        iv_len = cipher |> then(fn _ -> 16 end)

        ct =
          :crypto.crypto_one_time(aes_cbc_name(klen), key, :crypto.strong_rand_bytes(iv_len), pad7(data), true)

        _ = envs
        # php writes $sealdata/$envkeys by reference; the simple variant
        # returns the ciphertext (env keys ride the deferred ho channel)
        {:ok, {:string, ct}, i2}

      u ->
        u
    end
  rescue
    _ -> {:ok, {:bool, false}, i}
  end

  defp cipher_key_iv(name, i) do
    case Map.get(@ciphers, name) do
      {k, iv, _} -> {:ok, k, iv}
      nil -> warn_false(i, "openssl_seal(): Unknown cipher algorithm")
    end
  end

