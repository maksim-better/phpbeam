  # ────────────────────────── digests / random ──────────────────────────

  @digest_map %{
    "md5" => :md5, "sha1" => :sha, "sha256" => :sha256, "sha384" => :sha384,
    "sha512" => :sha512, "ripemd160" => :ripemd160, "md4" => :md4,
    "sha224" => :sha224, "sha3-256" => :sha3_256, "sha3-512" => :sha3_512
  }

  defp digest(vals, i) do
    data = str0(vals)
    algo = String.downcase(str_at(vals, 1, "sha256"))
    raw? = truthy_at(vals, 2)

    case Map.get(@digest_map, algo) do
      nil ->
        warn_false(i, "openssl_digest(): Unknown signature algorithm")

      a ->
        d = :crypto.hash(a, data)
        {:ok, {:string, if(raw?, do: d, else: Base.encode16(d, case: :lower))}, i}
    end
  end

  defp random_bytes(vals, i) do
    case Enum.at(vals, 0) do
      {:int, n} when n > 0 ->
        strong? = truthy_at(vals, 1)
        bin = if(strong?, do: :crypto.strong_rand_bytes(n), else: :crypto.strong_rand_bytes(n))
        {:ok, {:string, bin}, i}

      _ ->
        value_error(i, "openssl_random_pseudo_bytes(): Argument #1 ($length) must be greater than 0")
    end
  end

  defp pbkdf2(vals, i) do
    pw = str0(vals)
    salt = str_at(vals, 1, "")
    iters = int_at(vals, 2, 1)
    len = int_at(vals, 3, 0)
    algo = String.downcase(str_at(vals, 4, "sha1"))

    case Map.get(@digest_map, algo) do
      nil ->
        warn_false(i, "openssl_pbkdf2(): Unknown signature algorithm")

      a ->
        d = :crypto.pbkdf2_hmac(a, pw, salt, iters, max(len, 0))
        {:ok, {:string, Base.encode64(d)}, i}
    end
  end

  defp error_string(_vals, i), do: {:ok, {:bool, false}, i}

