  defp algo_name(:sha384), do: "sha384WithRSAEncryption"
  defp algo_name(:sha512), do: "sha512WithRSAEncryption"
  defp algo_name(_), do: "sha1WithRSAEncryption"

  defp sign(vals, i) do
    data = str0(vals)

    case key_arg(vals, 2, i) do
      {:ok, {:priv, key}, _ref} ->
        algo = algo_atom(Enum.at(vals, 3, {:int, 2}))
        sig = :public_key.sign(data, algo, key)
        # $signature is an by-reference OUTPUT arg (refs: [1]) — the engine
        # reads back by POSITION, so index 1 of new_vals must hold it
        new_vals = List.replace_at(Enum.take(vals, max(length(vals), 2)), 1, {:string, sig})
        {:ref_call, {:bool, true}, new_vals, i}

      {:ok, {:pub, _}, _ref} ->
        warn_false(i, "openssl_sign(): supplied key param cannot be coerced into a private key")

      u ->
        u
    end
  end

  defp verify(vals, i) do
    data = str0(vals)
    sig = str_at(vals, 1, "")

    case key_arg(vals, 2, i) do
      {:ok, {_, key}, _ref} ->
        algo = algo_atom(Enum.at(vals, 3, {:int, 2}))

        pub =
          case key do
            {:RSAPrivateKey, _v, n, e, _, _, _, _, _, _, _} -> {:RSAPublicKey, n, e}
            {:RSAPublicKey, _, _} = k -> k
          end

        {:ok, {:int, if(:public_key.verify(data, algo, sig, pub), do: 1, else: 0)}, i}

      u ->
        u
    end
  end

  # ────────────────────────── RSA encrypt pairs ──────────────────────────

  defp public_encrypt(vals, i), do: rsa_pair_run(:pub_enc, vals, i)
  defp private_decrypt(vals, i), do: rsa_pair_run(:priv_dec, vals, i)
  defp private_encrypt(vals, i), do: rsa_pair_run(:priv_enc, vals, i)
  defp public_decrypt(vals, i), do: rsa_pair_run(:pub_dec, vals, i)

  # php's encrypt/decrypt pairs take &$out by reference (position 1)
  defp rsa_pair_ref(which, vals, i) do
    case rsa_pair_run(which, vals, i) do
      {:ok, {:string, out}, i2} ->
        new_vals = List.replace_at(Enum.take(vals, max(length(vals), 2)), 1, {:string, out})
        {:ref_call, {:bool, true}, new_vals, i2}

      other ->
        other
    end
  end

  defp rsa_pair_run(which, vals, i) do
    data = str0(vals)

    # signature: (data, &$out, $key, $padding) — the key rides position 2
    case key_arg(vals, 2, i) do
      {:ok, {_kind, key}, _ref} ->
        pad = int_at(vals, 2, 1)

        out =
          case {which, pad} do
            {:pub_enc, 4} ->
              :public_key.encrypt_public(data, to_pub(key),
                rsa_padding: :rsa_pkcs1_oaep_padding
              )

            {:pub_enc, _} ->
              :public_key.encrypt_public(data, to_pub(key), rsa_padding: :rsa_pkcs1_padding)

            {:priv_dec, _} ->
              :public_key.decrypt_private(data, key, rsa_padding: :rsa_pkcs1_padding)

            {:priv_enc, _} ->
              :public_key.encrypt_private(data, key, rsa_padding: :rsa_pkcs1_padding)

            {:pub_dec, _} ->
              :public_key.decrypt_public(data, to_pub(key), rsa_padding: :rsa_pkcs1_padding)
          end

        {:ok, {:string, out}, i}

      u ->
        u
    end
  rescue
    _ -> {:ok, {:bool, false}, i}
  end

  defp to_pub({:RSAPrivateKey, _v, n, e, _, _, _, _, _, _, _}), do: {:RSAPublicKey, n, e}
  defp to_pub({:RSAPublicKey, _, _} = k), do: k

